import React, {
    useCallback,
    useEffect,
    useMemo,
    useState
} from "react";

const API_BASE = "/api/segmentation";

const SEGMENT_TYPES = [
    "code",
    "data",
    "stack",
    "heap",
    "shared",
    "custom"
];

const PERMISSIONS = [
    "r",
    "w",
    "x"
];

function formatNumber(value) {
    const number = Number(value);

    if (!Number.isFinite(number)) {
        return "0";
    }

    return number.toLocaleString();
}

function formatPercent(value) {
    const number = Number(value);

    if (!Number.isFinite(number)) {
        return "0.0%";
    }

    return `${number.toFixed(1)}%`;
}

function asArray(value) {
    return Array.isArray(value)
        ? value
        : [];
}

function normalizePermissions(value) {
    if (Array.isArray(value)) {
        return value.map(String);
    }

    if (typeof value === "string") {
        return value
            .split("")
            .filter((item) =>
                PERMISSIONS.includes(item)
            );
    }

    return [];
}

function getResponseData(payload) {
    if (
        payload &&
        typeof payload === "object" &&
        payload.data !== undefined
    ) {
        return payload.data;
    }

    return payload;
}

async function apiRequest(
    path,
    options = {}
) {
    const response = await fetch(
        `${API_BASE}${path}`,
        {
            headers: {
                "Content-Type":
                    "application/json",
                ...(options.headers || {})
            },
            ...options
        }
    );

    let payload = null;

    try {
        payload = await response.json();
    } catch {
        payload = null;
    }

    if (!response.ok) {
        throw new Error(
            payload?.error ||
            payload?.message ||
            `Request failed with status ${response.status}.`
        );
    }

    if (
        payload &&
        payload.success === false
    ) {
        throw new Error(
            payload.error ||
            payload.message ||
            "The segmentation request failed."
        );
    }

    return payload;
}

